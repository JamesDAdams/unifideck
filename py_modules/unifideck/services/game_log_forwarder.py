"""services/game_log_forwarder.py — Forward game.log to plugin logger on stop.

The launcher subprocess writes Proton/Wine/game stdout+stderr into
``~/.local/share/unifideck/launches/{launch_id}.game.log``.  That
process may not be able to reach the dev server (network isolation
inside pressure-vessel), so the plugin process — which *can* reach
the dev server — reads the most recent game.log after game_stopped
and logs its tail at ERROR level.  DevLogShipper then ships it.
"""
from __future__ import annotations

import logging
import time
from pathlib import Path
from typing import Any

from unifideck.core.types.events import Events
from unifideck.event_bus.event_bus_devex import auto_wire, subscribe

logger = logging.getLogger(__name__)

_LAUNCHES_DIR = Path("~/.local/share/unifideck/launches").expanduser()
_TAIL_LINES = 250
_MAX_AGE_SECONDS = 30.0


class GameLogForwarder:

    def __init__(self, bus: Any | None = None) -> None:
        self._bus = bus
        if bus is not None:
            auto_wire(self, bus)

    @subscribe(Events.GAME_STOPPED)
    async def _on_game_stopped(self, **kwargs: Any) -> None:
        store = kwargs.get("store", "?")
        game_id = kwargs.get("game_id", "?")
        try:
            self._forward_latest(f"{store}:{game_id}")
        except Exception:
            logger.debug("[GameLogForwarder] forward failed", exc_info=True)

    def _forward_latest(self, game_key: str) -> None:
        if not _LAUNCHES_DIR.is_dir():
            return
        # Check ~/steam-*.log generated by PROTON_LOG=1
        home_dir = Path.home()
        steam_logs = sorted(
            home_dir.glob("steam-*.log"),
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        )
        if steam_logs:
            sl = steam_logs[0]
            sl_age = time.time() - sl.stat().st_mtime
            if sl_age < 600.0:
                slt = sl.read_text(encoding="utf-8", errors="replace")
                sl_lines = slt.splitlines()
                logger.info("[GameLogForwarder] Proton log %s (%d lines, %.0fs old)", sl.name, len(sl_lines), sl_age)
                for line in sl_lines[-100:]:
                    logger.error("[%s] %s", sl.name, line)

        # Check for vendor client logs inside active prefixes
        prefixes_dir = Path("~/.local/share/unifideck/prefixes").expanduser()
        if prefixes_dir.is_dir():
            for vlog in sorted(prefixes_dir.glob("**/Rockstar Games/**/*.log"), key=lambda p: p.stat().st_mtime, reverse=True)[:3]:
                if time.time() - vlog.stat().st_mtime < 600.0:
                    try:
                        vlines = vlog.read_text(encoding="utf-8", errors="replace").splitlines()
                        logger.info("[GameLogForwarder] Vendor log %s (%d lines)", vlog.name, len(vlines))
                        for line in vlines[-50:]:
                            logger.error("[%s] %s", vlog.name, line)
                    except Exception:
                        pass

        # Check /tmp/unifideck-launcher-debug.log
        debug_log = Path("/tmp/unifideck-launcher-debug.log")
        if debug_log.is_file():
            dt = debug_log.read_text(encoding="utf-8", errors="replace")
            logger.info("[GameLogForwarder] /tmp debug log (%d lines):", len(dt.splitlines()))
            for line in dt.splitlines()[-20:]:
                logger.error("[launcher-debug] %s", line)

        # Find all log files (.log and .game.log) sorted newest first
        candidates = sorted(
            [p for p in _LAUNCHES_DIR.iterdir() if p.suffix == ".log" or p.name.endswith(".game.log")],
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        )
        if not candidates:
            logger.info("[GameLogForwarder] no log files found in %s", _LAUNCHES_DIR)
            return
        # Log the 5 most recent files and their ages for diagnosis
        for c in candidates[:5]:
            c_age = time.time() - c.stat().st_mtime
            logger.info("[GameLogForwarder] candidate: %s (%.0fs old, %d bytes)", c.name, c_age, c.stat().st_size)

        # Pick the newest file regardless of type
        newest = candidates[0]
        age = time.time() - newest.stat().st_mtime
        if age > 600.0:
            logger.warning(
                "[GameLogForwarder] newest log is %.0fs old (>600s), skipping tail", age,
            )
            return
        text = newest.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        logger.info(
            "[GameLogForwarder] %s — newest log %s (%d lines, %.0fs old)",
            game_key, newest.name, len(lines), age,
        )
        tail = lines[-_TAIL_LINES:]
        for line in tail:
            logger.error("[%s] %s", newest.name, line)

        # Also check if there's a paired .game.log or .log file
        pair_suffix = ".game.log" if not newest.name.endswith(".game.log") else ".log"
        base_name = newest.name.replace(".game.log", "").replace(".log", "")
        paired = _LAUNCHES_DIR / f"{base_name}{pair_suffix}"
        if paired.is_file() and paired != newest:
            pt = paired.read_text(encoding="utf-8", errors="replace")
            plines = pt.splitlines()
            logger.info(
                "[GameLogForwarder] paired log %s (%d lines)",
                paired.name, len(plines),
            )
            for line in plines[-_TAIL_LINES:]:
                logger.error("[%s] %s", paired.name, line)
